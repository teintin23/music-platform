CREATE TABLE app_user (
    user_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL UNIQUE,
    email          VARCHAR(100) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    is_admin       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_time   TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE artist (
    artist_id    INT PRIMARY KEY REFERENCES app_user(user_id) ON DELETE CASCADE,
    artist_name  VARCHAR(100) NOT NULL,
    avatar_url   VARCHAR(255),
    is_removed   BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE FUNCTION check_artist_not_admin() RETURNS trigger AS $$
BEGIN
    IF (SELECT is_admin FROM app_user WHERE user_id = NEW.artist_id) THEN
        RAISE EXCEPTION 'Admin account % cannot have an artist profile', NEW.artist_id;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_artist_not_admin
    BEFORE INSERT OR UPDATE ON artist
    FOR EACH ROW EXECUTE FUNCTION check_artist_not_admin();

CREATE TABLE genre (
    genre_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name  VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE album (
    album_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id  INT NOT NULL REFERENCES artist(artist_id),
    title      VARCHAR(150) NOT NULL,
    cover_url  VARCHAR(255)
);

CREATE TABLE song (
    song_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id       INT REFERENCES album(album_id),          -- NULL = single
    title          VARCHAR(150) NOT NULL,
    duration       INT NOT NULL CHECK (duration BETWEEN 15 AND 30),
    file_url       VARCHAR(255) NOT NULL UNIQUE,
    cover_url      VARCHAR(255),
    uploaded_time  TIMESTAMP NOT NULL DEFAULT now(),
    is_removed     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE song_artist (
    song_id      INT NOT NULL REFERENCES song(song_id) ON DELETE CASCADE,
    artist_id    INT NOT NULL REFERENCES artist(artist_id),
    credit_role  VARCHAR(10) NOT NULL CHECK (credit_role IN ('main', 'featured')),
    PRIMARY KEY (song_id, artist_id)
);

CREATE UNIQUE INDEX uq_song_one_main ON song_artist(song_id) WHERE credit_role = 'main';

CREATE TABLE song_genre (
    song_id   INT NOT NULL REFERENCES song(song_id) ON DELETE CASCADE,
    genre_id  INT NOT NULL REFERENCES genre(genre_id) ON DELETE RESTRICT, 
    PRIMARY KEY (song_id, genre_id)
);

CREATE TABLE follow (
    user_id        INT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    artist_id      INT NOT NULL REFERENCES artist(artist_id) ON DELETE CASCADE,
    followed_time  TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, artist_id)
);

CREATE TABLE liked_song (
    user_id     INT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    song_id     INT NOT NULL REFERENCES song(song_id) ON DELETE CASCADE,
    liked_time  TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, song_id)
);

CREATE TABLE playlist (
    playlist_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    name          VARCHAR(100) NOT NULL,
    is_public     BOOLEAN NOT NULL DEFAULT FALSE,
    created_time  TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE playlist_song (
    playlist_id  INT NOT NULL REFERENCES playlist(playlist_id) ON DELETE CASCADE,
    song_id      INT NOT NULL REFERENCES song(song_id) ON DELETE CASCADE,
    added_time   TIMESTAMP NOT NULL DEFAULT now(),
    position     INT NOT NULL CHECK (position >= 1),
    PRIMARY KEY (playlist_id, song_id),    
    CONSTRAINT uq_playlist_position UNIQUE (playlist_id, position) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE play (
    play_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    song_id          INT NOT NULL REFERENCES song(song_id),
    started_time     TIMESTAMP NOT NULL,
    second_listened  INT NOT NULL CHECK (second_listened BETWEEN 0 AND 30)
);
CREATE INDEX idx_play_started ON play(started_time);
CREATE INDEX idx_play_song    ON play(song_id, started_time);
CREATE INDEX idx_play_user    ON play(user_id, started_time);

CREATE TABLE chart (
    chart_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chart_type      VARCHAR(10) NOT NULL CHECK (chart_type IN ('song', 'artist', 'listener')),
    period          VARCHAR(15) NOT NULL CHECK (period IN ('last_7_days', 'current_month', 'all_time')),
    generated_time  TIMESTAMP NOT NULL
);

CREATE TABLE chart_entry (
    chart_id              INT NOT NULL REFERENCES chart(chart_id) ON DELETE CASCADE,
    chart_rank            INT NOT NULL CHECK (chart_rank BETWEEN 1 AND 10),
    song_id               INT REFERENCES song(song_id),
    artist_id             INT REFERENCES artist(artist_id),
    user_id               INT REFERENCES app_user(user_id),
    total_stream          INT NOT NULL CHECK (total_stream >= 0),
    distinct_listener     INT,
    total_listening_time  INT NOT NULL,
    reached_time          TIMESTAMP NOT NULL,
    previous_rank         INT,
    PRIMARY KEY (chart_id, chart_rank),
    CHECK (num_nonnulls(song_id, artist_id, user_id) = 1)
);
